"""Regenerate ``src/subpixelascii/_emoji_data.py`` from the Unicode emoji data file.

Usage: python tools/generate_emoji_table.py [VERSION]
"""

from __future__ import annotations

import sys
import urllib.request
from pathlib import Path

PROPERTIES = {"Emoji_Presentation", "Emoji_Modifier", "Regional_Indicator"}
OUTPUT = Path(__file__).resolve().parents[1] / "src" / "subpixelascii" / "_emoji_data.py"


def main() -> None:
    version = sys.argv[1] if len(sys.argv) > 1 else "18.0.0"
    url = f"https://www.unicode.org/Public/{version}/ucd/emoji/emoji-data.txt"
    with urllib.request.urlopen(url, timeout=60) as response:
        text = response.read().decode("utf-8")

    points: set[int] = set()
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        cps, prop = (part.strip() for part in line.split(";"))
        if prop not in PROPERTIES:
            continue
        lo, _, hi = cps.partition("..")
        points.update(range(int(lo, 16), int(hi or lo, 16) + 1))

    ranges: list[tuple[int, int]] = []
    for cp in sorted(points):
        if ranges and ranges[-1][1] == cp - 1:
            ranges[-1] = (ranges[-1][0], cp)
        else:
            ranges.append((cp, cp))

    body = "\n".join(f"    (0x{lo:05X}, 0x{hi:05X})," for lo, hi in ranges)
    OUTPUT.write_text(
        f'"""Code points that render as (colour) emoji by default.\n\n'
        f"Generated by tools/generate_emoji_table.py from Unicode {version} emoji-data.txt\n"
        f'({", ".join(sorted(PROPERTIES))}). Do not edit by hand.\n"""\n\n'
        f"EMOJI_PRESENTATION_RANGES: tuple[tuple[int, int], ...] = (\n{body}\n)\n",
        encoding="utf-8",
    )
    print(f"wrote {len(ranges)} ranges to {OUTPUT}")


if __name__ == "__main__":
    main()
